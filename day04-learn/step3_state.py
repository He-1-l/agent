# -*- coding: utf-8 -*-
"""
第 3 步：session_state —— 解决"脚本重跑，数据丢失"的问题

════════════════════════════════════════════════════════════
  问题回顾：
    每次交互，Streamlit 会把整个脚本从头执行一遍。
    那么普通变量每次都会被重新赋值，数据就丢了。

  比如：
    count = 0
    if st.button("+1"):
        count = count + 1
    st.write(count)
    → 无论点多少次，永远显示 1（因为每次重跑 count 都重置为 0）

  解决方案：
    st.session_state 是一个"跨重跑保留"的字典。

  运行：双击 run_step3.bat
════════════════════════════════════════════════════════════
"""
import streamlit as st

st.title("第 3 步：session_state")


# ==================================================================
# 对比实验 A：普通变量（会丢失）
# ==================================================================
st.header("❌ 对比实验 A：用普通变量")

st.write("下面这个计数器用的是普通变量，无论点多少次，它永远显示 1：")

plain_count = 0                                  # ← 每次重跑都重置为 0
if st.button("普通变量 +1"):
    plain_count = plain_count + 1
st.write(f"当前值：**{plain_count}**")
st.caption("原因：每次点击，脚本重头执行，plain_count 又被赋值为 0")


# ==================================================================
# 对比实验 B：session_state（能保留）
# ==================================================================
st.header("✅ 对比实验 B：用 session_state")

# ------------------------------------------------------------------
# TODO 1: 初始化 session_state
#   提示：判断 key 是否已存在，不存在则初始化
#      if "safe_count" not in st.session_state:
#          st.session_state["safe_count"] = 0 
#   把下面两行补完整
# ------------------------------------------------------------------
if "safe_count" not in st.session_state:
    st.session_state["safe_count"] = 0     # ← 初始值应该是 0

# ------------------------------------------------------------------
# TODO 2: 点击按钮时，让 session_state 里的值 +1
#   提示：st.session_state["safe_count"] += 1
# ------------------------------------------------------------------
if st.button("session_state +1"):
    st.session_state["safe_count"] += 1                              # ← 改成 +1 操作

st.write(f"当前值：**{st.session_state['safe_count']}**")
st.caption("这个值会跨重跑保留，点几次就是几")


# ==================================================================
# 实战：做一个简易聊天记录
# ==================================================================
st.divider()
st.header("实战：用 session_state 保存对话")

# ------------------------------------------------------------------
# TODO 3: 初始化消息列表
#   提示：如果 "messages" 不在 session_state 里，就设为空列表 []
# ------------------------------------------------------------------
if "messages" not in st.session_state:
    st.session_state["messages"] = []     # ← 改成空列表

# 显示历史消息
st.write("**历史消息：**")
if not st.session_state["messages"]:
    st.info("还没有消息，在下面输入试试")
else:
    for m in st.session_state["messages"]:
        st.write(f"- {m}")

# 输入框 + 按钮
# ------------------------------------------------------------------
# TODO 4: 创建输入框和"发送"按钮
#   提示：msg = st.text_input("说点什么")
#        if st.button("发送") and msg:  ...
# ------------------------------------------------------------------
msg = st.text_input("说点什么")                                    # ← 改成 st.text_input(...)
if st.button("发送"):
    if msg:                                   # 非空才添加
        # TODO 5: 把 msg 追加到 session_state 的 messages 列表
        #   提示：列表的 append 方法
        st.session_state["messages"].append(msg)                                  # ← 改成追加操作
        st.rerun()                            # 重跑一次，刷新显示


# ==================================================================
# 观察重点
# ==================================================================
st.divider()
st.write("""
**想清楚这三个问题：**

1. 为什么普通变量会丢失，而 session_state 不会？
   → 普通变量存在"这次执行"的栈里，执行完就销毁。
     session_state 存在"这个浏览器会话"里，跨执行保留。

2. `if "safe_count" not in st.session_state:` 这行为什么要判断？
   → 因为脚本每次重跑都会执行到这行。
     不判断的话，每次都会把值重置为 0，等于没用。

3. 这个机制和你要做的 RAG 界面有什么关系？
   → 对话历史就存在 session_state["messages"] 里。
     每次提问后追加，显示时遍历它。
""")
