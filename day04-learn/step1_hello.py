# -*- coding: utf-8 -*-
"""
第 1 步：最小 Streamlit 示例

════════════════════════════════════════════════════════════
  目标：理解"Streamlit 代码 = 网页内容"

  核心认知：
    Streamlit 的代码是【从上往下执行】的。
    每写一行 st.xxx()，网页上就多一个元素。
    没有 HTML，没有 CSS，纯 Python。

  运行：双击 run_step1.bat
════════════════════════════════════════════════════════════
"""
import streamlit as st

# ------------------------------------------------------------------
# TODO 1: 显示一个网页标题
#   提示：st.title("文字")   —— 会显示成最大的标题
#   把下面这行改成显示 "我的第一个网页"
# ------------------------------------------------------------------
st.title("我的第一个网页")


# ------------------------------------------------------------------
# TODO 2: 显示一段普通文字
#   提示：st.write("文字")
#   让网页显示 "我正在学 Streamlit"
# ------------------------------------------------------------------
st.write("我正在学streamlit")


# ------------------------------------------------------------------
# 下面这些是"给你看的"，不用改，运行后观察效果
# ------------------------------------------------------------------

st.header("这是二级标题")           # 比 title 小一号
st.subheader("这是三级标题")        # 再小一号

st.write("write 是最通用的函数，文字、数字、列表、字典都能显示：")
st.write(123)
st.write([1, 2, 3])
st.write({"name": "何焕", "age": 21})

st.markdown("**markdown 也支持**：可以加粗、加*斜体*、写[链接](https://streamlit.io)")

st.code("print('这是代码块')", language="python")

st.info("ℹ️ 这是一条信息提示")
st.success("✅ 这是一条成功提示")
st.warning("⚠️ 这是一条警告提示")
st.error("❌ 这是一条错误提示")

# 分隔线
st.divider()

st.caption("这是小字说明文字")

# ------------------------------------------------------------------
# 观察重点
# ------------------------------------------------------------------
st.write("---")
st.write("""
**观察这个网页，想三个问题：**

1. 我没有写任何 HTML，网页是怎么出来的？
   → Streamlit 帮你把 Python 调用翻译成了网页元素

2. 如果我把 st.title 那行删掉，网页会怎样？
   → 试试看，改完保存，网页会问你要不要重新运行（Rerun）

3. 代码顺序和网页上元素的顺序一致吗？
   → 一致的，从上往下
""")
