# -*- coding: utf-8 -*-
"""
第 2 步：让网页能"接收输入并响应"

════════════════════════════════════════════════════════════
  目标：理解 Streamlit 的"交互"机制

  核心认知：
    st.xxx_input() 这类函数会【返回用户输入的值】。
    你把它赋值给一个变量，就能在下文用。

    这和普通 Python 函数一样：
        name = input("请输入姓名：")     # 命令行版
        name = st.text_input("请输入姓名")  # 网页版

  运行：双击 run_step2.bat
════════════════════════════════════════════════════════════
"""
import streamlit as st

st.title("第 2 步：输入与响应")


# ==================================================================
# 输入控件 1：文本框
# ==================================================================
st.header("1. 文本框")

# ------------------------------------------------------------------
# TODO 1: 接收用户输入的姓名
#   提示：st.text_input("提示文字")  会返回用户输入的内容
#   把下面这行补全
# ------------------------------------------------------------------
name = st.text_input("请输入你的名字")          # ← 改成 st.text_input("请输入你的名字")

if name:
    st.success(f"你好，{name}！")
else:
    st.info("请在上面的框里输入你的名字")


# ==================================================================
# 输入控件 2：滑块（返回一个数字）
# ==================================================================
st.header("2. 滑块")

# ------------------------------------------------------------------
# TODO 2: 创建一个滑块
#   提示：st.slider("标签", 最小值, 最大值, 默认值)
#   要求：范围 0-100，默认 50
# ------------------------------------------------------------------
score = st.slider("值",0,100,50)         # ← 改成 st.slider(...)

if score is not None:
    st.write(f"你选择的值是：**{score}**")
    # 根据值显示不同内容（这就是"响应"）
    if score >= 80:
        st.success("优秀")
    elif score >= 60:
        st.warning("及格")
    else:
        st.error("不及格")


# ==================================================================
# 输入控件 3：下拉选择
# ==================================================================
st.header("3. 下拉选择")

# ------------------------------------------------------------------
# TODO 3: 创建一个下拉框
#   提示：st.selectbox("标签", ["选项1", "选项2", "选项3"])
#   选项内容：["粗排-only", "粗排+精排"]
# ------------------------------------------------------------------
mode = st.selectbox("下拉框",["粗排-only","粗排+精排","其他"])          # ← 改成 st.selectbox(...)

if mode:
    st.write(f"当前检索模式：**{mode}**")


# ==================================================================
# 输入控件 4：开关（返回 True/False）
# ==================================================================
st.header("4. 开关")

# ------------------------------------------------------------------
# TODO 4: 创建一个开关
#   提示：st.toggle("标签", value=True)   —— 默认打开
# ------------------------------------------------------------------
enabled = st.toggle("开关",value=True)       # ← 改成 st.toggle(...)

if enabled is not None:
    st.write(f"开关状态：**{'开' if enabled else '关'}**")


# ==================================================================
# 输入控件 5：按钮（返回 True/False，点一下为 True）
# ==================================================================
st.header("5. 按钮")

# ------------------------------------------------------------------
# TODO 5: 创建一个按钮
#   提示：st.button("按钮文字")   —— 被点击的那次运行为 True
# ------------------------------------------------------------------
clicked = st.button("点我")       # ← 改成 st.button("点我")

if clicked:
    st.balloons()        # 放气球动画（好玩但没用）
    st.success("你点击了按钮！")


# ==================================================================
# 观察重点
# ==================================================================
st.divider()
st.write("""
**观察这 5 个控件，想清楚：**

1. 每次你在网页上操作（输入、拖动、点击），
   整个 Python 脚本会【从头到尾重新执行一遍】。
   —— 这就是 Streamlit 的核心机制：**每次交互 = 重跑整个脚本**

2. 所以 `if name:` 这种判断才有意义 ——
   第一次运行时 name 是空字符串，所以不显示问候语。

3. 那问题来了：如果脚本每次都重跑，
   之前输入的对话历史怎么保存？
   —— 这就要用到 st.session_state，下一步会讲。
""")
